test('命名版本与定稿长期保留，日期校验、母子隔离及回收站恢复', t => {
  const root = fixture(t), store = new ResumeStore(root)
  let doc = store.create({ company: '版本验收', title: '产品', jd: '岗位要求' })
  assert.equal(doc.meta.notes, '')
  assert.equal(doc.meta.sent, '')
  const named = store.checkpoint(doc.id, { revision: doc.revision, label: '投递前版本' })
  assert.throws(() => store.checkpoint(doc.id, { revision: 'old', label: '陈旧' }), error => error.status === 409)
  const pdf = Buffer.from('%PDF-1.7\n/Type /Page\n原始定稿 bytes')
  const final = store.saveFinal(doc, pdf, { label: '第一次投递', date: '2026-10-07' })
  assert.throws(() => store.saveFinal(store.get('_master'), pdf, { label: '母版' }))
  for (let i = 0; i < 48; i++) doc = store.save(doc.id, { revision: doc.revision, markdown: '# 修改 ' + i, meta: { sent: '2026-10-07', followUp: '2026-10-14', notes: '' } })
  const history = store.history(doc.id)
  assert.equal(history.filter(item => !item.pinned).length, 40)
  assert.ok(history.some(item => item.version === named.version && item.label === '投递前版本'))
  assert.equal(store.version(doc.id, named.version).markdown, masterSource)
  assert.equal(store.get(doc.id).meta.notes, '') // 空备注不能吞掉后面的日期字段。
  assert.equal(store.get(doc.id).meta.followUp, '2026-10-14')
  assert.throws(() => store.save(doc.id, { revision: doc.revision, meta: { followUp: '2026-02-30' } }), /日期无效/)
  assert.throws(() => store.saveFinal({ ...doc, revision: 'old' }, pdf, { label: '旧窗口' }), error => error.status === 409)
  assert.deepEqual(store.finalPdf(doc.id, final.version), pdf)
  assert.equal(store.final(doc.id, final.version).markdown, masterSource)
  store.nameVersion(doc.id, named.version, { label: '长期保留的改名' })
  assert.equal(store.version(doc.id, named.version).label, '长期保留的改名')
  store.archive(doc.id, doc.revision)
  store.restoreTrash(store.trash()[0].key)
  assert.deepEqual(store.finalPdf(doc.id, final.version), pdf)
  assert.equal(store.get('_master').markdown, masterSource)
  assert.ok(fs.readFileSync(path.join(root, 'resumes/INDEX.md'), 'utf8').includes('2026-10-14'))
})

test('逐行比较重建准确，大文件有界；状态、公司分组和跟进筛选', () => {
  const before = '第一行\r\n旧成果\r\n相同\r\n结尾', after = '第一行\n新增成果\n相同\n补充\n结尾'
  const diff = lineDiff(before, after)
  assert.equal(diff.filter(row => row.type !== 'add').map(row => row.text).join('\n'), before.replaceAll('\r\n', '\n'))
  assert.equal(diff.filter(row => row.type !== 'remove').map(row => row.text).join('\n'), after)
  const large = lineDiff(Array.from({ length: 1500 }, (_, i) => '旧 ' + i).join('\n'), Array.from({ length: 1500 }, (_, i) => '新 ' + i).join('\n'))
  assert.equal(large.filter(row => row.type === 'add').length, 1500)
  const docs = [
    { id: '_master', master: true, meta: {} },
    { id: '公司A-运营', meta: { company: '公司A', title: '运营', status: '已投递', followUp: localDate(), notes: '' } },
    { id: '公司A-产品', meta: { company: '公司A', title: '产品', status: '已关闭', followUp: localDate(), notes: '' } },
    { id: '公司B-已归档', archived: true, meta: { company: '公司B', title: '运营', status: '已投递', followUp: localDate(), notes: '' } },
  ]
  const due = filterDocuments(docs, { follow: 'due', group: 'company' })
  assert.equal(due.due, 1)
  assert.deepEqual(due.filtered.map(doc => doc.id), ['_master', '公司A-运营'])
  assert.equal(due.groups.get('公司A').length, 1)
  assert.deepEqual(filterDocuments(docs, { status: '已关闭' }).filtered.map(doc => doc.id), ['_master', '公司A-产品'])
  assert.deepEqual(filterDocuments(docs, { archive: 'archived' }).filtered.map(doc => doc.id), ['_master', '公司B-已归档'])
  assert.equal(filterDocuments(docs, { archive: 'all' }).filtered.length, 4)
  assert.equal(filterDocuments(docs, { archive: 'all', follow: 'due' }).due, 1)
  assert.equal(filterDocuments(docs, { archive: 'all', follow: 'week' }).filtered.some(doc => doc.archived), false)
})

test('真实 PDF 定稿重启后可下载，旧校样提示更新，ZIP 可恢复全部持久数据', async t => {
  const root = fixture(t, true)
  let app = createApp({ root }), url = await listenForBrowser(app.server), setup = await (await fetch(url + '/api/bootstrap')).json()
  t.workflowCleanup.push(() => new Promise(resolve => { app.server.close(resolve); app.server.closeAllConnections() }))
  const request = (route, method = 'GET', body) => fetch(url + route, { method, headers: { 'Content-Type': 'application/json', 'X-Local-Token': setup.token }, body: body === undefined ? undefined : JSON.stringify(body) })
  let doc = app.store.create({ company: '档案验收', title: '运营', jd: '原始 JD' }), route = '/api/documents/' + encodeURIComponent(doc.id)
  const response = await request(route + '/finals', 'POST', { revision: doc.revision, label: '正式投递版', date: '2026-10-07' })
  assert.equal(response.status, 201, await response.clone().text())
  const final = await response.json()
  const original = app.store.finalPdf(doc.id, final.version)
  assert.equal(original.subarray(0, 5).toString(), '%PDF-')
  assert.ok(original.length > 8000)
  assert.equal(app.store.get(doc.id).proof.current, true)
  const named = await (await request(route + '/history', 'POST', { revision: doc.revision, label: '重要节点' })).json()
  assert.equal(named.pinned, true)
  assert.equal((await request(route + '/history/' + named.version, 'PATCH', { label: '重要节点改名' })).status, 200)
  doc = app.store.save(doc.id, { revision: doc.revision, jd: '新的 JD', meta: { sent: '2026-10-07', followUp: '2026-10-14' } })
  assert.equal(doc.proof.current, true, '只改 JD 或投递状态不使简历校样失效')
  doc = app.store.save(doc.id, { revision: doc.revision, markdown: masterSource + '\n- 后续新增成果\n' })
  assert.equal(doc.proof.current, false)
  const newer = await request(route + '/export', 'POST', { revision: doc.revision })
  assert.equal(newer.status, 200)
  assert.notDeepEqual(Buffer.from(await newer.arrayBuffer()), original)
  assert.deepEqual(app.store.finalPdf(doc.id, final.version), original)
  fs.appendFileSync(path.join(root, 'assets/styles/classic.css'), '\n/* 外部主题变化 */\n')
  assert.equal(app.store.get(doc.id).proof.current, false)
  await new Promise(resolve => { app.server.close(resolve); app.server.closeAllConnections() })
  app = createApp({ root }); url = await listenForBrowser(app.server); setup = await (await fetch(url + '/api/bootstrap')).json()
  const link = await (await request(route + '/finals/' + final.version, 'POST', {})).json()
  assert.deepEqual(Buffer.from(await (await fetch(url + link.url)).arrayBuffer()), original)
  assert.equal((await request(route + '/finals/' + encodeURIComponent('../escape'), 'POST', {})).status, 400)
  const trash = app.store.create({ company: '回收记录', title: '岗位' }); app.store.archive(trash.id, trash.revision)
  app.store.setArchived(doc.id, { revision: app.store.get(doc.id).revision, archived: true })
  fs.mkdirSync(path.join(root, '.local/exports'), { recursive: true }); fs.writeFileSync(path.join(root, '.local/exports/temporary.txt'), '排除')
  fs.writeFileSync(path.join(root, '.env'), 'SECRET=test-only')
  fs.writeFileSync(path.join(root, '.local/server.log'), '排除日志')
  const backup = await (await request('/api/backup', 'POST', {})).json()
  const archiveResponse = await fetch(url + backup.url)
  assert.equal(archiveResponse.headers.get('content-type'), 'application/zip')
  const zip = await JSZip.loadAsync(Buffer.from(await archiveResponse.arrayBuffer()), { checkCRC32: true })
  const archiveFiles = Object.keys(zip.files)
  for (const required of ['src/server.mjs', 'package-lock.json', 'assets/fonts/SourceHanSansCN-Regular.ttf', 'resumes/_master/resume.md', '恢复备份说明.txt', 'BACKUP-INFO.json']) assert.ok(zip.file(required), required)
  assert.ok(archiveFiles.some(file => file.startsWith('.local/history/')))
  assert.ok(archiveFiles.some(file => file.startsWith('.local/trash/')))
  assert.ok(archiveFiles.some(file => file.startsWith('.local/finals/') && file.endsWith('resume.pdf')))
  assert.ok(!archiveFiles.includes('.env'))
  assert.ok(!archiveFiles.includes('.local/exports/temporary.txt'))
  assert.ok(!archiveFiles.includes('web/visual-editor.bundle.js'))
  const restored = fs.mkdtempSync(path.join(base, 'workflow-test-restored-'))
  t.after(() => { assert.ok(restored.startsWith(base + path.sep)); fs.rmSync(restored, { recursive: true, force: true }) })
  for (const [name, entry] of Object.entries(zip.files)) {
    assert.ok(!name.startsWith('/') && !name.split('/').includes('..'))
    const file = path.join(restored, name)
    if (entry.dir) fs.mkdirSync(file, { recursive: true })
    else { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, await entry.async('nodebuffer')) }
  }
  const restoredStore = new ResumeStore(restored)
  assert.deepEqual(restoredStore.finalPdf(doc.id, final.version), original)
  assert.equal(restoredStore.version(doc.id, named.version).label, '重要节点改名')
  assert.equal(restoredStore.get(doc.id).meta.followUp, '2026-10-14')
  assert.equal(restoredStore.get(doc.id).archived, true)
  assert.equal(restoredStore.trash().length, 1)
  assert.equal(restoredStore.get('_master').markdown, masterSource)
})

