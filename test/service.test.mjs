const project = path.resolve(import.meta.dirname, '..')
function fixture(t, full = false) {
  const base = path.join(project, '.local')
  fs.mkdirSync(base, { recursive: true })
  const root = fs.mkdtempSync(path.join(base, 'test-'))
  fs.mkdirSync(path.join(root, 'resumes', '_master'), { recursive: true })
  fs.writeFileSync(path.join(root, 'resumes', '_master', 'resume.md'), '# 测试姓名\n\n> 本地联系方式\n\n## [[e618]] 经历\n\n- 原始内容\n')
  fs.cpSync(path.join(project, 'assets', full ? '' : 'styles'), path.join(root, 'assets', full ? '' : 'styles'), { recursive: true })
  if (full) fs.cpSync(path.join(project, 'web'), path.join(root, 'web'), { recursive: true })
  t.after(() => {
    assert.ok(root.startsWith(base + path.sep))
    fs.rmSync(root, { recursive: true, force: true })
  })
  return root
}

test('完整复制、母子隔离、同名保护、历史恢复与回收站', t => {
  const root = fixture(t)
  const store = new ResumeStore(root)
  const master = store.get('_master')
  const child = store.create({ company: '测试公司', title: '产品运营', jd: 'JD 原文' })
  assert.equal(child.markdown, master.markdown)
  assert.equal(child.jd, 'JD 原文')
  assert.throws(() => store.create({ company: '测试公司', title: '产品运营' }), e => e.status === 409)
  store.save('_master', { revision: master.revision, markdown: '# 母版新的内容' })
  assert.equal(store.get(child.id).markdown, child.markdown)
  const saved = store.save(child.id, { revision: child.revision, markdown: '# 子版独立修改', theme: 'serif', meta: { status: '面试中', notes: '下周跟进' } })
  assert.equal(saved.meta.status, '面试中')
  assert.equal(store.history(child.id).length, 1)
  assert.throws(() => store.save(child.id, { revision: child.revision, markdown: '# 陈旧窗口' }), e => e.status === 409)
  assert.equal(store.get(child.id).markdown, saved.markdown)
  const old = store.version(child.id, store.history(child.id)[0].version)
  const restored = store.save(child.id, { ...old, revision: saved.revision }, '恢复历史前备份')
  assert.equal(restored.markdown, child.markdown)
  assert.equal(store.history(child.id).length, 2)
  assert.throws(() => store.archive('_master', store.get('_master').revision))
  store.archive(child.id, restored.revision)
  assert.throws(() => store.get(child.id), e => e.status === 404)
  assert.equal(store.trash().length, 1)
  assert.equal(store.restoreTrash(store.trash()[0].key).markdown, child.markdown)
  assert.equal(store.history(child.id).length, 2)
  assert.equal(store.trash().length, 0)
  assert.ok(fs.readFileSync(path.join(root, 'resumes/INDEX.md'), 'utf8').includes('测试公司'))
  assert.throws(() => store.get('../resumes'), e => e.status === 400)
  assert.throws(() => store.create({ company: '.hidden', title: '职位' }))
  assert.equal(localDate(new Date(2026, 9, 6, 0, 5)), '2026-10-06')
})

test('归档独立于投递状态，内容保存、历史、定稿、复制和删除恢复保留正确归类', t => {
  const root = fixture(t), store = new ResumeStore(root)
  let doc = store.create({ company: '归档验收', title: '岗位', jd: '完整 JD' })
  doc = store.save(doc.id, { revision: doc.revision, meta: { status: '面试中', followUp: localDate(), notes: '保留记录' } })
  const settingsFile = path.join(root, 'resumes', doc.id, '.webui.json')
  fs.writeFileSync(settingsFile, JSON.stringify({ theme: 'classic', custom: '保留设置' }))
  doc = store.get(doc.id)
  const named = store.checkpoint(doc.id, { revision: doc.revision, label: '归档前版本' })
  const pdf = Buffer.from('%PDF-1.7\n/Type /Page\n保留定稿')
  const final = store.saveFinal(doc, pdf, { label: '已投递定稿' })
  assert.throws(() => store.setArchived('_master', { revision: store.get('_master').revision, archived: true }), /母版不能归档/)
  assert.throws(() => store.setArchived(doc.id, { revision: 'old', archived: true }), e => e.status === 409)
  assert.throws(() => store.setArchived(doc.id, { revision: doc.revision, archived: 'yes' }), /归档状态无效/)
  const archived = store.setArchived(doc.id, { revision: doc.revision, archived: true })
  assert.equal(archived.archived, true)
  assert.equal(archived.markdown, doc.markdown)
  assert.equal(archived.jd, doc.jd)
  assert.deepEqual(archived.meta, doc.meta)
  assert.notEqual(archived.revision, doc.revision)
  assert.ok(fs.existsSync(path.join(root, 'resumes', doc.id, 'resume.md')))
  assert.equal(store.trash().length, 0)
  assert.ok(store.list().find(item => item.id === doc.id).archived)
  fs.mkdirSync(path.join(root, 'src'))
  fs.copyFileSync(path.join(project, 'src/apps.mjs'), path.join(root, 'src/apps.mjs'))
  execFileSync(process.execPath, [path.join(root, 'src/apps.mjs'), 'index'], { cwd: root })
  assert.ok(fs.readFileSync(path.join(root, 'resumes/INDEX.md'), 'utf8').includes('| 面试中 | 已归档 |'), '命令行总览也保留归档列')
  assert.equal(store.setArchived(doc.id, { revision: archived.revision, archived: true }).revision, archived.revision)
  assert.throws(() => store.save(doc.id, { revision: doc.revision, markdown: '# 旧窗口' }), e => e.status === 409)
  doc = store.save(doc.id, { revision: archived.revision, markdown: '# 归档后修订', theme: 'serif' })
  assert.equal(doc.archived, true)
  assert.equal(JSON.parse(fs.readFileSync(settingsFile)).custom, '保留设置')
  const old = store.version(doc.id, named.version)
  doc = store.save(doc.id, { ...old, revision: doc.revision }, '恢复内容')
  assert.equal(doc.archived, true, '恢复历史内容不恢复归档分类')
  assert.deepEqual(store.finalPdf(doc.id, final.version), pdf)
  assert.equal(store.create({ source: doc.id, company: '新投递', title: '岗位' }).archived, false)
  store.moveToTrash(doc.id, doc.revision)
  assert.throws(() => store.get(doc.id), e => e.status === 404)
  doc = store.restoreTrash(store.trash()[0].key)
  assert.equal(doc.archived, true)
  assert.equal(doc.meta.status, '面试中')
  assert.equal(store.version(doc.id, named.version).label, '归档前版本')
  assert.deepEqual(store.finalPdf(doc.id, final.version), pdf)
  doc = store.setArchived(doc.id, { revision: doc.revision, archived: false })
  assert.equal(doc.archived, false)
  assert.equal(doc.meta.status, '面试中')
  assert.equal(new ResumeStore(root).get(doc.id).archived, false)
})

test('两套主题共用渲染、CSS 顺序与本地字体路径检查', t => {
  const root = fixture(t, true)
  const htmlPath = path.join(root, 'resumes/_master/resume.html')
  for (const theme of ['classic', 'serif']) {
    const { html, css } = renderResume({ root, markdown: '# 中文简历\n\n## [[e618]] 工作\n\n<style>body { --text-size: 11pt; }</style>\n', theme, htmlPath })
    assert.ok(html.includes('../../assets/icons/e618.png'))
    assert.ok(css.includes('../../assets/fonts/SourceHanSansCN-Regular.ttf'))
    assert.ok(css.indexOf('/* Text */') < css.indexOf('/* Custom Configs */'))
    assert.ok(html.indexOf('--text-size: 11pt') > html.indexOf('/* Custom Configs */'))
    if (theme === 'serif') assert.ok(css.includes("--title-font: 'SourceHanSerifCN'"))
  }
  assert.throws(() => renderResume({ root, markdown: '# 测试', theme: '../main', htmlPath }))
  fs.unlinkSync(path.join(root, 'assets/fonts/SourceHanSansCN-Regular.ttf'))
  assert.throws(() => renderResume({ root, markdown: '# 测试', htmlPath }), /字体文件路径解析不到/)
})

test('HTTP API、冲突保护、图片验证、本机边界与真实 PDF 导出', async t => {
  const root = fixture(t, true)
  const { server, store } = createApp({ root })
  const base = await listenForBrowser(server)
  t.after(() => new Promise(resolve => { server.close(resolve); server.closeAllConnections() }))
  const setup = await (await fetch(base + '/api/bootstrap')).json()
  const request = (url, method, body, extra = {}) => fetch(base + url, { method, headers: { 'Content-Type': 'application/json', 'X-Local-Token': setup.token, ...extra }, body: body == null ? undefined : JSON.stringify(body) })
  assert.equal(setup.documents[0].id, '_master')
  assert.equal((await fetch(base + '/api/health')).status, 200)
  assert.equal((await fetch(base + '/')).status, 200)
  assert.equal((await fetch(base + '/api/documents', { headers: { Origin: 'https://example.com' } })).status, 403)
  const badHostStatus = await new Promise(resolve => { const req = http.get(base + '/api/documents', { headers: { Host: 'evil.example' } }, res => { res.resume(); resolve(res.statusCode) }); req.on('error', () => resolve(0)) })
  assert.equal(badHostStatus, 403)
  assert.equal((await fetch(base + '/api/documents', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' })).status, 403)
  assert.equal((await fetch(base + '/resumes/_master/resume.md')).status, 404)
  assert.equal((await fetch(base + '/assets/%2e%2e/%2e%2e/package.json')).status, 404)
  const createdRes = await request('/api/documents', 'POST', { company: 'API 验收', title: '岗位', jd: '职位原文' })
  assert.equal(createdRes.status, 201)
  const created = await createdRes.json()
  const docUrl = '/api/documents/' + encodeURIComponent(created.id)
  assert.equal((await request('/api/documents', 'POST', { company: 'API 验收', title: '岗位' })).status, 409)
  let result = await request(docUrl, 'PUT', { revision: created.revision, markdown: '# 更新后的中文姓名\n\n## [[e618]] 工作经验\n\n- 保存结果\n', theme: 'serif', jd: '完整职位原文', meta: { status: '已投递' } })
  assert.equal(result.status, 200)
  const saved = await result.json()
  assert.equal((await request(docUrl, 'PUT', { revision: created.revision, markdown: '# 陈旧内容' })).status, 409)
  assert.equal((await request('/api/upload', 'POST', { data: 'data:image/png;base64,' + Buffer.from('not a real image').toString('base64') })).status, 400)
  const imageData = 'data:image/png;base64,' + fs.readFileSync(path.join(project, 'assets/avatar.png')).toString('base64')
  const imageRes = await request('/api/upload', 'POST', { data: imageData })
  assert.equal(imageRes.status, 201)
  const image = await imageRes.json()
  assert.equal((await fetch(base + '/' + image.path)).status, 200)
  const preview = await (await request('/api/render', 'POST', { markdown: saved.markdown, theme: 'serif' })).json()
  assert.ok(preview.html.includes("script-src 'none'"))
  assert.ok(preview.html.includes('更新后的中文姓名'))
  const pdfRes = await request(docUrl + '/export', 'POST', { revision: saved.revision })
  assert.equal(pdfRes.status, 200, JSON.stringify(await (pdfRes.status === 200 ? Promise.resolve('') : pdfRes.json())))
  const pdf = Buffer.from(await pdfRes.arrayBuffer())
  assert.equal(pdf.subarray(0, 5).toString(), '%PDF-')
  assert.ok(pdf.length > 8000)
  assert.ok(pdf.toString('latin1').includes('/MediaBox [0 0 594.95996 841.91998]') || /\/MediaBox\s*\[0 0 59[45]/.test(pdf.toString('latin1')))
  assert.ok(fs.existsSync(path.join(root, 'resumes', created.id, 'resume.pdf')))
  assert.equal(store.get(created.id).markdown, saved.markdown)
  const webExport = await request(docUrl + '/export', 'POST', { revision: saved.revision }, { Accept: 'application/json' })
  assert.equal(webExport.status, 200)
  const webDownload = await webExport.json()
  assert.equal(webDownload.pages, 1)
  const downloadablePdf = await fetch(base + webDownload.url)
  assert.equal(downloadablePdf.headers.get('content-type'), 'application/pdf')
  assert.ok(downloadablePdf.headers.get('content-disposition').includes('attachment'))
  assert.equal(Buffer.from(await downloadablePdf.arrayBuffer()).subarray(0, 5).toString(), '%PDF-')
  const mdDownload = await (await request('/api/downloads', 'POST', { filename: '测试.md', text: '# 中文内容' })).json()
  assert.equal(await (await fetch(base + mdDownload.url)).text(), '# 中文内容')
  const jdDownload = await (await request('/api/downloads', 'POST', { filename: '岗位-JD.txt', text: '岗位原文\n职责要求' })).json()
  const jdText = await fetch(base + jdDownload.url)
  assert.equal(jdText.headers.get('content-type'), 'text/plain; charset=utf-8')
  assert.equal(await jdText.text(), '岗位原文\n职责要求')
  const history = await (await fetch(base + docUrl + '/history')).json()
  const restoreRes = await request(docUrl + '/restore', 'POST', { revision: saved.revision, version: history[0].version })
  assert.equal(restoreRes.status, 200)
  const restored = await restoreRes.json()
  assert.equal(restored.markdown, created.markdown)
  assert.equal((await fetch(base + docUrl + '/archived', { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ revision: restored.revision, archived: true }) })).status, 403)
  assert.equal((await request(docUrl + '/archived', 'PATCH', { revision: created.revision, archived: true })).status, 409)
  const archivedRes = await request(docUrl + '/archived', 'PATCH', { revision: restored.revision, archived: true })
  assert.equal(archivedRes.status, 200)
  const archived = await archivedRes.json()
  assert.equal(archived.archived, true)
  assert.equal(archived.markdown, restored.markdown)
  assert.equal((await request(docUrl + '/trash', 'POST', { revision: restored.revision })).status, 409)
  assert.equal((await request(docUrl + '/trash', 'POST', { revision: archived.revision })).status, 200)
  const trash = await (await fetch(base + '/api/trash')).json()
  const recovered = await request('/api/trash/' + trash[0].key, 'POST', {})
  assert.equal(recovered.status, 200)
  assert.equal((await recovered.json()).archived, true)
  assert.equal((await request(docUrl + '/archive', 'POST', { revision: store.get(created.id).revision })).status, 200, '旧版本接口仍执行移入回收站')
})
