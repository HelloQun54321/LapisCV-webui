test('排版设置只维护一个受控 CSS 块，保留自定义规则并验证输入范围', () => {
  const original = '# 姓名\n\n<style>body { --text-size: 9pt; }</style>\n\n## 经历\n'
  const first = writeLayout(original, { textSize: 11, lineHeight: 1.6 })
  const second = writeLayout(first, { textSize: 12, lineHeight: 1.7 })
  assert.equal((second.match(/data-webui-layout/g) || []).length, 1)
  assert.ok(second.includes('<style>body { --text-size: 9pt; }</style>'))
  assert.ok(second.includes('--text-size: 12pt'))
  assert.ok(!removeLayout(second).includes('data-webui-layout'))
  assert.throws(() => writeLayout(original, { textSize: 999 }), /6–24/)
  assert.throws(() => writeLayout(original, { accent: 'red; display:none' }), /主题色/)
})

