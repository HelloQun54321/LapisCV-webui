import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { createApp } from '../src/server.mjs'
import { findBrowser, launchBrowser } from '../src/browser.mjs'
import { buildWeb } from '../src/build-web.mjs'
import { listenForBrowser } from './local-server.mjs'

const project = path.resolve(import.meta.dirname, '..')
test('对象编辑修复：精细尺寸与偏移、保留属性、连续撤销、横线、链接、图片与表格', async t => {
  await buildWeb()
  const base = path.join(project, '.local'), root = fs.mkdtempSync(path.join(base, 'objects-test-'))
  assert.ok(root.startsWith(base + path.sep))
  const raw = '# 对象验收\n\n<img class="avatar" id="portrait" src="assets/avatar.png" style="width:15mm;height:20mm">\n\n<h2 id="experience" class="my-heading">工作经历</h2>\n\n<div class="entry-title"><h3>第一段经历</h3><p>2026</p></div>\n\n- **成果条目**\n\n[主页](https://example.com/old)\n\n<img class="logo" width="120" height="160" src="assets/avatar.png">\n\n| 名称 | 日期 |\n| --- | --- |\n| 项目 | 2026 |\n\n<div class="custom"><p>保留内容</p></div>\n\n## 专业技能\n\n- 技能条目\n'
  fs.mkdirSync(path.join(root, 'resumes/_master'), { recursive: true })
  fs.writeFileSync(path.join(root, 'resumes/_master/resume.md'), raw)
  for (const name of ['assets', 'web']) fs.cpSync(path.join(project, name), path.join(root, name), { recursive: true })
  const { server, store } = createApp({ root }); const url = await listenForBrowser(server), browser = await launchBrowser(findBrowser())
  t.after(async () => { await browser.close(); await new Promise(resolve => { server.close(resolve); server.closeAllConnections() }); assert.ok(root.startsWith(base + path.sep)); fs.rmSync(root, { recursive: true, force: true }) })
  const page = await browser.newPage(), errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewport({ width: 1440, height: 1000 }); await page.goto(url, { waitUntil: 'networkidle0' })
  const frame = () => page.frames().find(f => f.parentFrame())
  await page.waitForFunction(() => document.querySelector('#preview').contentDocument?.querySelector('.resume-editor'))
  await page.click('#properties-toggle')
  await page.$eval('#visual-link', el => { el.closest('details').open = true })
  const ready = () => page.waitForFunction(() => document.querySelector('#preview').contentDocument?.querySelector('.resume-editor[contenteditable="true"] h1'))
  const change = async (selector, value) => page.$eval(selector, (el, value) => { el.closest('details')?.setAttribute('open', ''); el.value = String(value); if (!el.checkValidity()) throw new Error('Invalid control: ' + el.outerHTML); el.dispatchEvent(new Event('change', { bubbles: true })) }, value)
  const selectText = async selector => { await frame().click(selector); await frame().$eval(selector, el => { const range = document.createRange(); range.selectNodeContents(el); const selection = window.getSelection(); selection.removeAllRanges(); selection.addRange(range) }) }
  await ready()
  await change('[data-layout="avatarWidth"]', 17.8)
  let dimensions = await frame().$eval('.avatar', el => { const s = getComputedStyle(el); return [parseFloat(s.width), parseFloat(s.height)] })
  assert.ok(Math.abs(dimensions[0] * 25.4 / 96 - 17.8) < .02)
  assert.ok(Math.abs(dimensions[1] / dimensions[0] - 4/3) < .002, '锁定比例应同时改变高度')
  assert.equal(await frame().$eval('.avatar', el => el.id), 'portrait')
  await frame().click('.avatar')
  const grip = await frame().$('[data-handle="resize"]'), box = await grip.boundingBox()
  await page.mouse.move(box.x + 4, box.y + 4); await page.mouse.down(); await page.mouse.move(box.x + 12, box.y + 4, { steps: 5 }); await page.mouse.up()
  assert.ok(await frame().$eval('.avatar', el => parseFloat(getComputedStyle(el).width) * 25.4 / 96 > 19), '拖拽手柄应调整实际图片尺寸')
  assert.ok(await frame().$eval('.avatar', el => { const css = getComputedStyle(el); return Math.abs(parseFloat(css.height) / parseFloat(css.width) - 4/3) < .002 }), '拖拽的宽高比例不能受头像边框影响')
  await page.click('[data-format="undo"]')
  assert.equal(await frame().$eval('.avatar', el => el.style.width), '17.8mm', '整个拖拽缩放只占一步撤销')
  const x = await frame().$eval('.avatar', el => el.getBoundingClientRect().x)
  await page.click('[data-nudge="left:-0.1"]')
  assert.ok(Math.abs((await frame().$eval('.avatar', el => el.getBoundingClientRect().x)) - x + .1 * 96/25.4) < .03)
  await change('[data-image="top"]', .5)
  assert.equal(await frame().$eval('.avatar', el => el.style.top), '0.5mm')
  await change('[data-layout="cropX"]', 20)
  assert.equal(await frame().$eval('.avatar', el => getComputedStyle(el).objectPosition), '20% 50%')
  await page.click('#source-mode'); await page.click('#visual-mode'); await ready()
  assert.equal(await frame().$eval('.avatar', el => el.style.top), '0.5mm')
  await frame().click('h1'); await page.keyboard.type('修改')
  await page.waitForFunction(() => document.querySelector('#preview').contentDocument.querySelector('h1').textContent.includes('修改'))
  const avatarPath = await frame().$eval('.avatar', el => el.getAttribute('src'))
  await (await page.$('#avatar-file')).uploadFile(path.join(root, 'assets/avatar.png'))
  await page.waitForFunction(() => document.querySelector('#preview').contentDocument.querySelector('.avatar').getAttribute('src').includes('uploads/'))
  assert.equal(await frame().$eval('.avatar', el => el.style.width), '17.8mm', '替换保留原图尺寸')
  await page.click('[data-format="undo"]')
  assert.equal(await frame().$eval('.avatar', el => el.getAttribute('src')), avatarPath)
  await page.click('[data-format="undo"]')
  assert.equal(await frame().$eval('h1', el => el.textContent), '对象验收', '替换图片后仍可撤销之前的文字编辑')
  await page.click('#source-mode'); await page.click('#visual-mode'); await ready()
  await page.click('[data-format="undo"]')
  assert.equal(await frame().$eval('.avatar', el => getComputedStyle(el).objectPosition), '50% 50%', '模式切换不清空撤销')
  await page.click('#source-mode')
  await page.$eval('#editor', el => { el.value = el.value.replace('对象验收', '源码修改'); el.dispatchEvent(new Event('input', { bubbles: true })) })
  await page.click('#visual-mode'); await ready()
  assert.equal(await frame().$eval('h1', el => el.textContent), '源码修改')
  await page.click('[data-format="undo"]')
  assert.equal(await frame().$eval('h1', el => el.textContent), '对象验收', '源码编辑应成为可撤销的一步')
  await selectText('h2#experience'); await page.click('[data-format="bold"]'); await page.click('[data-format="clear"]')
  assert.equal(await frame().$eval('h2#experience', el => el.textContent), '工作经历')
  assert.equal(await frame().$eval('h2#experience', el => el.className), 'my-heading')
  await change('[data-rule="width"]', 60); await change('[data-rule="thickness"]', .4); await change('[data-rule="y"]', 1.2)
  assert.ok(await frame().$eval('h2#experience', el => parseFloat(getComputedStyle(el, '::after').borderTopWidth) >= 1)) // 浏览器边框按设备像素取整。
  assert.ok(await frame().$eval('h2#experience', el => Math.abs(parseFloat(getComputedStyle(el, '::after').width) / el.getBoundingClientRect().width - .6) < .01))
  assert.equal(await frame().$$eval('h2[data-resume-rule]', els => els.length), 1, '单个章节修改不能污染其他章节')
  await page.click('[data-outline-transfer="0"]'); await page.select('#transfer-section', '1'); await page.$eval('#transfer-form', el => el.requestSubmit())
  assert.ok(await frame().$eval('.entry-title', el => { let previous = el.previousElementSibling; while (previous && previous.tagName !== 'H2') previous = previous.previousElementSibling; return previous?.textContent.includes('专业技能') }), '经历应能跨章节移动')
  await page.click('[data-format="undo"]')
  const attributeCheck = await page.evaluate(async () => {
    const { VisualEditor } = await import('/visual-editor.bundle.js'), el = document.createElement('div'); document.body.append(el)
    const editor = new VisualEditor({ element: el, markdown: '<p lang="zh" data-note="保留"><span class="detail" style="letter-spacing:.2px">内容</span> <a class="site" title="主页" target="_self" href="https://example.com">链接</a></p>\n' })
    editor.editor.commands.setTextSelection({ from: 1, to: 3 }); editor.command('bold'); editor.command('fontSize', '11.3')
    const text = editor.getMarkdown(); editor.destroy(); el.remove(); return text
  })
  for (const value of ['lang="zh"', 'data-note="保留"', 'class="detail"', 'letter-spacing: 0.2px', 'class="site"', 'title="主页"', 'target="_self"', '11.3pt']) assert.ok(attributeCheck.includes(value), attributeCheck)
  await frame().click('a'); await page.click('#visual-link')
  assert.equal(await page.$eval('#link-url', el => el.value), 'https://example.com/old')
  await page.$eval('#link-url', el => { el.value = 'https://example.com/new' }); await page.$eval('#link-form', el => el.requestSubmit())
  assert.equal(await frame().$eval('a', el => el.getAttribute('href')), 'https://example.com/new')
  await frame().click('a'); await page.click('#visual-link'); await page.click('#unlink')
  assert.equal(await frame().$('a'), null); await page.click('[data-format="undo"]')
  await frame().click('img.logo'); await change('[data-picture="width"]', 37.7)
  assert.equal(await frame().$eval('img.logo', el => el.getAttribute('height')), '160')
  await frame().click('td p'); await page.keyboard.type('可编辑')
  assert.ok(await frame().$eval('td', el => el.textContent.includes('可编辑')))
  await page.$eval('[data-table="row-add"]', el => { el.closest('details').open = true }); await page.click('[data-table="row-add"]'); await page.click('[data-table="column-add"]')
  assert.equal(await frame().$$eval('tr', els => els.length), 3); assert.equal(await frame().$$eval('tr:first-child > *', els => els.length), 3)
  await frame().click('.custom', { count: 2 })
  await page.$eval('#raw-source', el => { el.value = '<div class="custom"><p>已修改的自定义块</p></div>\n' }); await page.$eval('#raw-form', el => el.requestSubmit())
  assert.equal(await frame().$eval('.custom', el => el.textContent), '已修改的自定义块')
  await frame().click('h2:last-of-type'); await page.keyboard.press('End'); await page.click('#visual-divider')
  assert.ok(await frame().$('.resume-divider'))
  await frame().click('.resume-divider'); await change('[data-rule="width"]', 75)
  assert.equal(await frame().$eval('.resume-divider', el => el.style.getPropertyValue('--resume-rule-width')), '75%')
  await page.click('#save-button'); await page.waitForFunction(() => document.querySelector('#save-state').textContent === '已保存')
  const saved = store.get('_master').markdown
  assert.match(saved, /id="experience"/); assert.match(saved, /class="my-heading"/); assert.match(saved, /class="logo"/); assert.match(saved, /width="120"/); assert.match(saved, /height="160"/)
  assert.match(saved, /resume-divider/); assert.match(saved, /已修改的自定义块/)
  await page.click('#proof-button'); await page.waitForSelector('.pdf-proof-page[data-ready="true"]', { timeout: 15000 })
  assert.equal(await page.$$eval('.pdf-proof-page', els => els.length), 1, '装饰横线不能触发 PDF 换页')
  await page.screenshot({ path: path.join(base, 'qa-object-pdf.png') })
  await page.click('#proof-back'); await page.reload({ waitUntil: 'networkidle0' }); await ready()
  assert.equal(await frame().$$eval('h2', els => els.length), 2, '自定义 HTML 与装饰线编辑后章节仍应正常解析')
  assert.equal(await frame().$eval('.avatar', el => el.style.width), '17.8mm')
  assert.equal(await frame().$eval('img.logo', el => el.style.width), '37.7mm')
  assert.equal(await frame().$eval('h2#experience', el => el.style.getPropertyValue('--resume-rule-width')), '60%')
  await frame().click('.resume-divider'); await change('[data-rule="width"]', 65)
  assert.equal(await frame().$eval('.resume-divider', el => el.style.getPropertyValue('--resume-rule-width')), '65%', '重新打开后独立横线仍可编辑')
  await page.screenshot({ path: path.join(base, 'qa-object-editing.png') })
  assert.deepEqual(errors, [])
})
