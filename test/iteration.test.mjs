import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { execFileSync, spawnSync } from 'node:child_process'
import { finishIteration, nextVersion } from '../src/iterate.mjs'
import { setupGit } from '../src/setup-git.mjs'

const project = path.resolve(import.meta.dirname, '..')
test('迭代命令在真实 Git 仓库中递增、提交、打标签并保护失败与无关改动', t => {
  const base = path.join(project, '.local')
  fs.mkdirSync(base, { recursive: true })
  const root = fs.mkdtempSync(path.join(base, 'iteration-test-'))
  t.after(() => { assert.ok(root.startsWith(base + path.sep)); fs.rmSync(root, { recursive: true, force: true }) })
  const git = args => execFileSync('git', args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim()
  const write = (file, value) => fs.writeFileSync(path.join(root, file), value)
  fs.mkdirSync(path.join(root, 'src'))
  fs.mkdirSync(path.join(root, 'test'))
  fs.mkdirSync(path.join(root, '.githooks'))
  for (const name of ['check-release.mjs', 'check-publication.mjs', 'setup-git.mjs', 'iterate.mjs']) fs.copyFileSync(path.join(project, 'src', name), path.join(root, 'src', name))
  fs.copyFileSync(path.join(project, '.githooks/pre-commit'), path.join(root, '.githooks/pre-commit'))
  fs.chmodSync(path.join(root, '.githooks/pre-commit'), 0o755)
  write('.gitignore', '.local/\n')
  write('package.json', JSON.stringify({ name: 'iteration-fixture', version: '1.0.0', type: 'module' }))
  write('package-lock.json', JSON.stringify({ name: 'iteration-fixture', version: '1.0.0', lockfileVersion: 3, packages: { '': { name: 'iteration-fixture', version: '1.0.0' } } }))
  write('CHANGELOG.md', '# CHANGELOG\n\n## [1.0.0] - 2026-10-06\n\n- baseline\n')
  write('note.md', 'original\n')
  write('test/smoke.test.mjs', "import test from 'node:test'; import assert from 'node:assert/strict'; test('fixture smoke', () => assert.ok(true));\n")
  git(['init', '-b', 'test-iteration'])
  git(['config', 'user.name', 'Iteration Test'])
  git(['config', 'user.email', 'iteration-test@example.invalid'])
  git(['add', '.'])
  git(['commit', '-m', 'fixture baseline'])
  const baseline = git(['rev-parse', 'HEAD'])
  assert.equal(setupGit(root), true)
  if (process.platform !== 'win32') assert.equal(fs.statSync(path.join(root, '.githooks/pre-commit')).mode & 0o111, 0o111, '初始化应确保 Linux/macOS 提交钩子可执行')
  write('note.md', 'new content\n')
  git(['add', 'note.md'])
  const bypassAttempt = spawnSync('git', ['commit', '-m', 'missing version'], { cwd: root, encoding: 'utf8' })
  assert.notEqual(bypassAttempt.status, 0)
  assert.match(bypassAttempt.stderr, /没有递增版本号/)
  assert.equal(git(['rev-parse', 'HEAD']), baseline)
  const result = finishIteration({ root, summary: '验证自动版本与提交', files: ['note.md'] })
  assert.equal(result.version, '1.0.1')
  assert.equal(JSON.parse(fs.readFileSync(path.join(root, 'package.json'))).version, '1.0.1')
  assert.equal(git(['rev-parse', 'v1.0.1']), git(['rev-parse', 'HEAD']))
  assert.match(git(['log', '-1', '--format=%s']), /v1\.0\.1 验证自动版本与提交/)
  assert.equal(git(['status', '--porcelain']), '')
  assert.throws(() => finishIteration({ root, summary: '没有改动', files: ['note.md'] }), /没有改动/)
  write('note.md', 'another edit\n')
  write('test/smoke.test.mjs', "throw new Error('expected test failure');\n")
  const beforeFailure = git(['rev-parse', 'HEAD'])
  assert.throws(() => finishIteration({ root, summary: '不能提交失败的验证', files: ['note.md'] }), /验证未通过/)
  assert.equal(git(['rev-parse', 'HEAD']), beforeFailure)
  assert.equal(JSON.parse(fs.readFileSync(path.join(root, 'package.json'))).version, '1.0.1')
  write('other.md', 'user change\n')
  git(['add', 'other.md'])
  assert.throws(() => finishIteration({ root, summary: '不能混入用户改动', files: ['note.md'] }), /本次范围以外/)
  assert.ok(git(['diff', '--cached', '--name-only']).includes('other.md'))
  assert.equal(nextVersion('2.0.1', 'patch'), '2.0.2')
  assert.equal(nextVersion('2.0.1', 'minor'), '2.1.0')
  assert.equal(nextVersion('2.0.1', 'major'), '3.0.0')
})
